#!/usr/bin/env node
/**
 * Bundle @shadow/intake-kit for GitHub Pages intake (docs/demo-intake-profile.js).
 * Browser adapter keeps answersObj API used by demo-intake-app.js.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '../../..');
const KIT = path.join(ROOT, 'shadow-corpus/packages/intake-kit/lib');
const OUT = path.join(ROOT, 'docs/demo-intake-profile.js');

function varNameFor(relPath) {
  return `kit_${relPath.replace(/\.cjs$/, '').replace(/-/g, '_')}`;
}

function bundleEntry(entry, registry = new Map()) {
  if (registry.has(entry)) return registry.get(entry);

  const abs = path.join(KIT, entry);
  let src = fs.readFileSync(abs, 'utf8');
  const depMatches = [...src.matchAll(/require\(['"]\.\/([^'"]+)['"]\)/g)];
  const depVars = [];
  for (const [, dep] of depMatches) {
    const bundled = bundleEntry(dep, registry);
    if (!depVars.some((d) => d.dep === dep)) {
      depVars.push({ dep, varName: bundled.varName });
    }
  }

  for (const { dep, varName } of depVars) {
    src = src.replace(
      new RegExp(`require\\(['"]\\.\\/${dep.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}['"]\\)`, 'g'),
      varName
    );
  }

  src = src.replace(/^'use strict';\s*/m, '');
  const exportVar = varNameFor(entry);
  src = src.replace(/module\.exports\s*=\s*/, `const ${exportVar} = `);

  const record = { entry, varName: exportVar, src: src.trim() };
  registry.set(entry, record);
  return record;
}

function inlineKit() {
  const registry = new Map();
  bundleEntry('index.cjs', registry);
  const order = [
    'schema.cjs',
    'utils.cjs',
    'maps-to-reducer.cjs',
    'tension-detectors.cjs',
    'shadow-preview.cjs',
    'build-full-profile.cjs',
    'index.cjs'
  ];
  return order
    .filter((e) => registry.has(e))
    .map((e) => `// ${e}\n${registry.get(e).src}`)
    .join('\n\n');
}

const BROWSER_ADAPTER = `
function getAnswer(answersObj, id) {
  const a = answersObj[id];
  if (!a) return null;
  return {
    question_id: id,
    answer: {
      optionKey: typeof a.value === 'string' && a.value.length === 1 ? a.value : undefined,
      value: a.value,
      orderedKeys: Array.isArray(a.value) ? a.value : undefined
    },
    duration_ms: a.durationMs || 0
  };
}

function answersToArray(answersObj) {
  return Object.keys(answersObj || {}).map((id) => getAnswer(answersObj, id)).filter(Boolean);
}

function buildFullProfile({
  session_id,
  layerA = {},
  selectedTags = [],
  answersObj = {},
  domainDetect = null,
  meta = {}
}) {
  const questionAnswers = answersToArray(answersObj);
  const scenarioFromText = domainDetect
    ? {
        domain: domainDetect.top,
        top: domainDetect.top,
        conf: domainDetect.conf,
        confidence: domainDetect.confidence,
        scenario_primary: domainDetect.top,
        scenario_weights: domainDetect.scenario_weights || null,
        label: domainDetect.label || null
      }
    : null;

  return kit_build_full_profile.buildFullProfile({
    session_id,
    layerA,
    selectedTags,
    questionAnswers,
    questions: (typeof window !== 'undefined' && window.ShadowIntakeQuestions?.QUESTIONS) || [],
    scenarioFromText,
    meta: {
      ...meta,
      answered: Object.keys(answersObj || {}).length
    }
  });
}
`;

function main() {
  const header = `/**
 * AUTO-GENERATED by npm run build:intake-browser — do not edit by hand.
 * Canonical logic: shadow-corpus/packages/intake-kit/
 */
'use strict';
`;

  const body = `${header}
(function (global) {
${inlineKit()}

${BROWSER_ADAPTER}

global.ShadowIntakeProfile = {
  buildFullProfile,
  buildShadowPreview: kit_shadow_preview.buildShadowPreview,
  tagsByCategory: kit_utils.tagsByCategory,
  SCENARIO_DOMAINS: kit_build_full_profile.SCENARIO_DOMAINS,
  FULL_PROFILE_SCHEMA_VERSION: kit_schema.FULL_PROFILE_SCHEMA_VERSION
};
})(typeof window !== 'undefined' ? window : globalThis);
`;

  fs.writeFileSync(OUT, body);
  console.log(`wrote ${path.relative(ROOT, OUT)}`);
}

main();
